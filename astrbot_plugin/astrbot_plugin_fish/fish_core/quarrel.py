"""挨骂了该多凶：把「凶不凶」的判断从提示词挪进代码。

以前那套三级阶梯（c9bd3e8 版）是 1326 字的提示词。fish 的人设一共才 595 字，
照搬等于翻倍，而且模型每一轮都要在「这算第几级」上反复权衡，回话反而变软、变慢。

这里只保留三件事：
  1. classify()：用词表 + 指向判断这一句属于哪一档（0 不动 / 2 毒舌 / 3 开喷）。
     「指向」是关键——别人互骂、吐槽第三方一律 0，这条是 c9 版靠提示词做不到的。
  2. hint()：真触发了才往这一轮的 user_prompt 里塞一小段一次性指令。
     常态请求一个字都不多，不加常驻提示词，不拖垮闲聊。
  3. soften()：模型写嗨了带出直白脏话时降级成谐音（傻逼→煞笔），
     而不是把整句丢掉重来——丢掉会让它越答越短，最后只剩一句「急什么」。
"""

from __future__ import annotations

import random
import re
import time

# ---------------------------------------------------------------- 口径
# 一档：调侃。不注入任何指令，靠人设自己傲娇，注入了反而变成「被骂必回」的客服
_SOFT = ("菜", "笨", "蠢", "傻鱼", "人机", "下头", "弱", "憨", "小丑")

# 二档：阴阳怪气。要连续两轮同一个人，或者明确 @ 我，才值得还嘴
# 注意别用单字：「典」会把「经典语录」「字典」全算成阴阳，「孝」会撞「孝顺」。
# 今晚 22:47 就是这么把一句「算了，使出经典语录」判成被阴阳的
_TAUNT = ("就这", "典中典", "太典", "急了", "孝子", "大孝", "破防", "舔狗", "乐子",
          "笑死", "不行啊", "666")

# 三档：指名道姓的骂。只有这一档才开喷
_CURSE = ("傻逼", "傻b", "s b", "sb", "煞笔", "沙比", "脑瘫", "脑残", "弱智",
          "弱纸", "废物", "废柴", "死全家", "去死", "死吧", "滚蛋", "滚出去",
          "孤儿", "下贱", "贱种", "垃圾玩意", "畜生",
          # 之前漏了最常用来骂机器人的这批：@它骂「操你妈」它一声不吭，
          # 说句「闭嘴」反倒开喷，群里立刻被当成欺软怕硬
          "操你", "草你", "草泥马", "日你", "你妈死", "尼玛", "妈的",
          "tm的", "他妈的", "智障", "神经病", "没用的东西", "死开")

# 不带脏字但确实在骂：眼瞎 / 滚 / 算个什么东西 / 肥头大耳。
# 这类词单独出现不算（「这游戏真蠢」），必须配上「指的就是它」才成立
# 只用多字词：单字「肥」会把「大肥鱼」自己判成挨骂，「蠢」会把「这游戏真蠢」也算上
_BITE = ("眼瞎", "瞎了", "什么东西", "算个什么", "肥头大耳", "滚出去", "滚蛋",
         "装什么", "有病", "脑子", "蠢货", "笨蛋", "菜鸡", "弱鸡", "丑八怪", "闭嘴", "滚",
         # 点名骂鱼本身：22:52 群里甩了一句「傻鱼」，它按「接话质量 0.37」安静略过，
         # 看着就像挨骂不还嘴。这些词必须算挨骂
         "傻鱼", "臭鱼", "死鱼", "胖鱼", "笨鱼", "蠢鱼")

# 邀架：群里常见的「和鱼对骂」「来骂一架」，是让对方先动手，它必须接，
# 不接就成了木头——今晚两次测试全卡在这
_DUEL = re.compile(r"(对骂|互骂|来骂|骂一架|骂鱼)")

# 护主：骂到 life 头上，火气直接拉满（旧 bot 的护短铁律，实测群里最吃这套）
# 「老板」不能算主人：群里一句「我老板真是个傻逼」会把鱼直接送进三档开喷。
# 只认主人、创作者本身
_OWNER = ("life", "主人")

# 「骂的是我」的硬指向：只认点名，不认泛指的「你」。
# 用「你」判会误伤——群友互骂「你个傻逼」时鱼冲进去开喷，比不骂更丢人
_ME_STRONG = ("肥鱼", "傻鱼", "小鲸鱼", "鲸鱼", "这鱼", "bot", "机器人")
# 阴阳怪气可以放宽一点：泛指的「你」+ 连着两轮才够味
_ME_SOFT = _ME_STRONG + ("你",)

# 出口降级表。注意：这张表只给出口用，绝不塞进提示词——
# 给模型看见等于教它骂得更准，正好反了
#
# 顺序有讲究：组合词必须排在单字/双字前面。
# 旧表把 ("你妈","泥马") 放在 ("操你","草你") 之前，于是「操你妈」先变成「操泥马」，
# 轮到「操你」时已经匹配不上，动词原封不动留在原地 —— 实测出口仍是标准脏话。
_SOFTEN = (
    # 一、整句脏话组合：先整体换掉，别让后面的单字规则把它拆碎
    ("操你妈", "草泥嘛"), ("草你妈", "草泥嘛"), ("日你妈", "日泥马"),
    ("操你全家", "草泥全家"), ("你妈死了", "泥马四了"), ("尼玛死了", "泥马四了"),
    ("你妈死", "泥马四"), ("死全家", "四全家"),
    ("草泥马", "草泥嘛"),
    # 二、双字脏词
    ("傻逼", "煞笔"), ("傻b", "煞笔"), ("傻B", "煞笔"), ("沙比", "煞笔"),
    ("sb", "煞笔"), ("SB", "煞笔"), ("脑瘫", "脑摊"), ("脑残", "脑摊"),
    # 「废物」谐音成「费物」看着像打错字；换成同样带刺、读出来不别扭的说法
    ("弱智", "弱纸"), ("废物", "废东西"),
    ("去死", "去屎"), ("死吧", "屎吧"),
    ("你妈", "泥马"), ("你爸", "泥爸"), ("他妈", "他喵"),
    ("孤儿", "咕儿"), ("下贱", "下溅"), ("贱种", "溅种"),
    ("操你", "草你"), ("日你", "日泥"),
    ("妈的", "马的"), ("滚蛋", "滚单"),
)

# 谐音之后仍然不能发的：诅咒、死亡、坟头。短信按句切，命中整句丢掉
_HARD = re.compile(r"(死全家|死光|断子绝孙|坟|骨灰|尸体|去死|上吊)")

# 降级后仍无话可说时的兜底嘴替。故意不带任何雷区，也故意短
_QUIPS = (
    "急得跳脚像个小丑",
    "出门没带脑子就别出来叫唤",
    "你这话说得，纯种小脑萎缩",
    "就这点火气，还不够我甩尾巴的",
    "你算个什么勾八",
    "嘴比脑子快，说的就是你",
)

_SPLIT = re.compile(r"(?<=[，。！？；,.!?;])")

# 同一个人多久内允许几次开喷：超过就自动降到二档。
# 不留这个，对方连着阴阳十句，它就连喷十句，群友看到的是个坏掉的复读机
_L3_WINDOW = 300.0
_L3_MAX = 2

_L3_TS: dict[str, list[float]] = {}


def _norm(text: str) -> str:
    return re.sub(r"\s+", " ", str(text or "")).lower()


_ASCII_WORD = re.compile(r"[a-z0-9]+")


def _has(words, low: str) -> str:
    """分词命中：英文短词必须独立，中文照旧按子串。

    「sb」这种两字母裸子串会把 absbase、sbus、iOSb 全判成骂人
    （实测「absbase」被判三档开喷），而「你个sb」又要认。
    所以英文词卡两侧不能是字母/数字，中文词没有分词概念仍然直接 in。
    """
    for w in words:
        if not w:
            continue
        if w.isascii():
            if re.search(rf"(?<![a-z0-9]){re.escape(w)}(?![a-z0-9])", low):
                return w
        elif w in low:
            return w
    return ""


def classify(text: str, *, at_me: bool = False, mentions_owner: bool = False,
             consecutive: bool = False, reply_to_me: bool = False) -> int:
    """一句群消息该用多大的火回。返回 0/2/3（一档不注入，按 0 处理）。

    reply_to_me：这条像是在对它说（回它、或它刚说完话）

    at_me：这条 @ 了我 / 或者明显在说「你」
    mentions_owner：提到了 life / 主人
    consecutive：同一人上一句就已经在阴阳了
    """
    low = _norm(text)
    if not low:
        return 0

    curse = _has(_CURSE, low)
    # reply_to_me：这条是在回它、或者它刚说完话。群里骂人一半不带 @，
    # 少了这条，「你他妈傻逼」这种明摆着骂它的还要被当空气
    strong = at_me or reply_to_me or bool(_has(_ME_STRONG, low))
    soft = strong or bool(_has(_ME_SOFT, low))
    owner = mentions_owner or bool(_has(_OWNER, low))

    if _DUEL.search(low) and (strong or "鱼" in low):
        # 邀架：别人点名要骂它，退一步就成了软蛋
        return 3

    if curse:
        # 三档必须有明确指向：@了它、叫了它的名字/外号、或者骂到主人头上。
        # 光靠「它 25 秒内说过话」不够——群里那 25 秒里任何人互怼都会被算到它头上，
        # 「你有病吧」「闭嘴」这种日常互呛立刻变成它插进去开喷
        if at_me or bool(_has(_ME_STRONG, low)) or owner:
            return 3
        # 「你个傻逼鱼」既不 @ 也没喊外号，脏词挂在「鱼」上就是骂它。
        # 漏了这条它会一声不吭挨骂，看着像没长耳朵
        if "鱼" in low and re.search(r"你|这|那|条|个", low):
            return 3
        if reply_to_me:
            return 2
        # 骂的是别人：不关我事。硬接会变成「见谁咬谁」，比不接更毁人设
        return 0

    # 脏词优先于不带脏字的攻击词：顺序反了会出「大肥鱼你个煞笔」判成 2 档这种笑话
    bite = _has(_BITE, low)
    # 「臭鱼一条」「笨蛋鱼」这类不带 @ 的：只要带「鱼」就算指着它，
    # 它是条鱼，群里骂鱼不骂它骂谁
    if bite and (strong or "鱼" in low or (soft and consecutive)):
        return 2

    if _has(_TAUNT, low) and (soft or consecutive):
        return 2

    return 0


def gate(key: str, level: int) -> int:
    """同一个人五分钟内最多开喷两次，超过降成二档。"""
    if level < 3:
        return level
    now = time.time()
    ts = [t for t in _L3_TS.get(key, []) if now - t < _L3_WINDOW]
    _L3_TS[key] = ts
    if len(ts) >= _L3_MAX:
        return 2
    ts.append(now)
    return 3


def hint(level: int, nick: str, *, owner: bool = False, anger: bool = False) -> str:
    """只在真触发的那一轮附加的一次性指令。不加常驻提示词。"""
    if level < 2:
        return ""
    who = nick or "这个人"
    tail = "挑着用，别照抄；一句顶回去就够：" + " / ".join(random.sample(_QUIPS, 3))
    if level == 3:
        head = (f"【{who}刚指名骂了你" if not owner
                else f"【{who}刚指名骂了你主人 life")
        body = (head + "】回击只针对他，别牵连旁边搭话的。用老网民对线的力道喷回去，"
                "短促有力，别解释别讲道理别装大度，一句顶死；最多两条，骂完就停。"
                "不许扯家人、不许诅咒、不许往下三路走。" + tail)
        if anger:
            body += "【本群红温不设限】"
        return body
    return (f"【{who}在阴阳你】毒舌拆他就行，别用脏字，别讲道理，一句戳穿他装的那点东西，"
            "最多一条。" + tail)


# 换完一遍后仍残留的直白脏字（表没覆盖到的新变体）。命中就不发了，别硬顶
_RESIDUAL = ("操你", "草你", "日你", "傻逼", "脑残", "脑瘫", "废物", "他妈的", "死全家")


def soften(text: str) -> str:
    """出口降级：直白脏话换谐音；换完还带诅咒的整句丢掉。

    两个坑都在这里踩过：
      1) 纯表情/纯标点（「😅」「。。。」）本来完全无害，旧代码替换后判「没有中文英文数字」，
         就随机挑一句 _QUIPS 顶上去 —— 出口加工自己制造出人身攻击。所以先原样放行。
      2) 一张表只过一遍会漏（「操你妈」被「你妈→泥马」拆碎后「操你」匹配不上），
         改成替换到不再变化为止（最多 4 轮），最后再复查残留。
    清干净后如果什么都不剩，返回空串让上层静默——不再拿嘴替兜底，兜底本身就带攻击性。
    """
    out = str(text or "")
    if not out:
        return out
    # 没有可说的字（纯表情/纯标点/纯空白）：不属于要软化的内容，原样发
    if not re.search(r"[\u4e00-\u9fa5A-Za-z0-9]", out):
        return out
    for _ in range(4):
        before = out
        for bad, good in _SOFTEN:
            if bad in out:
                out = out.replace(bad, good)
        if out == before:
            break
    if _HARD.search(out):
        keep = [seg for seg in _SPLIT.split(out) if seg and not _HARD.search(seg)]
        out = "".join(keep).strip()
    if not out or _HARD.search(out) or any(b in out for b in _RESIDUAL):
        return ""
    return out


def looks_abusive(text: str) -> bool:
    """给 favor/巡检复用：这句是不是在骂人（不看指向）。"""
    low = _norm(text)
    return bool(_has(_CURSE, low))
