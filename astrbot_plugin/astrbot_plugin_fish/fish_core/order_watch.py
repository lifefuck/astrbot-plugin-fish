"""秩序巡检：只做两件事——粗筛「值不值得看一眼」，以及给模型一句判定用的提示词。

为什么要单独一层：原来上报全靠模型在回复里打 [REPORT:..] 标签，可模型只有在「要接话」
时才被调用。群里对着骂、刷广告的时候，鱼常常判「@的是别人」「质量分不够」就 return 了，
一次模型都没调过，标签自然不会出现——所以永远不告状。这条链路必须跟接话判定解耦。

这里也不做最终判断：粗筛只决定要不要花一次模型调用，判罚仍然交给模型。
"""

# 骂人的词根：只用来触发「看一眼」，命中不等于违规（朋友之间天天这么说话）
_ABUSE = (
    "操你", "草你", "你妈", "煞笔", "傻逼", "死全家", "去死", "杂种", "狗东西",
    "脑残", "废物点心", "nmsl", "cnm", "ntmd", "sb玩意",
)
# 引流特征：拉群、私聊、返利、刷单这类，正常聊天几乎不会连着出现
_AD = (
    "加群", "加我", "加v", "加V", "私聊我", "私我", "扫码", "进群领", "免费领",
    "日入", "月入", "兼职", "刷单", "返利", "代刷", "推广位", "点我主页", "t.me/",
    "微信", "vx号", "扣1", "扣一",
)


def suspicious(text: str, recent: list = None) -> str:
    """粗筛。返回命中的类别提示，空串表示「不用看」。"""
    t = str(text or "").strip()
    if len(t) < 2:
        return ""
    low = t.lower()
    if any(w in low for w in _AD):
        return "广告拉人"
    # 同一个人连着复制同一句话：刷屏
    if recent:
        same = [r for r in recent[-4:] if str(r).strip() == t and len(t) >= 4]
        if len(same) >= 2:
            return "刷屏"
    if any(w in low for w in _ABUSE):
        return "辱骂"
    return ""


JUDGE_SYSTEM = """你是 QQ 群秩序巡检，只判断一句话要不要报给群管。三种情况才算：
1. 广告拉人：拉群、加好友、引流、推销、返利刷单这类目的明确的推广；
2. 暴力刷屏：同一条内容反复刷、表情包轰炸式连发；
3. 严重辱骂这只机器人：冲着它本人的人身攻击、诅咒家人、下流羞辱。

以下一律不算，哪怕脏话很重：
- 群友之间互骂、开玩笑、打赌、游戏里喷人；
- 自称「我是傻逼」「我妈都不认识我」这种自嘲；
- 讨论「告状」「举报」这两个词本身，或者问这功能怎么用；
- 只是情绪上来的一句口头脏话；
- 骂的是别的机器人或别人，不是这一只；
- 只是一句「这 bot 好烦」「烦死了」这种随口吐槽——被嫌弃是常事，
  除非同时带人身攻击或家人诅咒，否则不值得惊动群管。

宁可漏报也别误报：群管被假警报吵两次，这功能就废了。

只输出一个词：YES 或 NO。"""


def judge_prompt(hint: str, nick: str, text: str, bot_nick: str, at_bot: bool = False) -> str:
    target = "这句话是直接 @ 着机器人说的" if at_bot else "这句话没有 @ 机器人，可能是对着别人说的"
    return (
        f"机器人自己叫「{bot_nick}」。\n"
        f"粗筛把它标成了「{hint}」，但粗筛只管字面像不像。\n"
        f"{target}。\n"
        f"发言人：{nick}\n消息：{text}\n"
        f"判断：这句话属于上面三种要报的情况吗？"
    )


